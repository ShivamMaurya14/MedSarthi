// Wait for DOM to load
document.addEventListener("DOMContentLoaded", async () => {
    // 1. Mock "Login" to fetch patient dat
    const patientId = "P-889012";
    await loadPatientData(patientId);

    // 2. Initialize Vapi AI Voice Button
    setupVapi();
});

async function loadPatientData(patientId) {
    try {
        const response = await fetch(`/patient-profile/${patientId}`);
        if (!response.ok) throw new Error("Network response was not ok");

        const resData = await response.json();
        const data = resData.data;

        // Populate fields
        document.getElementById("welcome-name").innerText = data.name.split(" ")[0];
        document.getElementById("user-name").innerText = data.name;
        document.getElementById("user-avatar").innerText = data.name.substring(0, 2).toUpperCase();
        document.getElementById("user-id").innerText = `ID: ${data.patient_id}`;

        document.getElementById("user-age").innerText = `${data.age} yrs`;
        document.getElementById("user-history").innerText = data.history[0];
        document.getElementById("report-title").innerText = data.latest_report.split("-")[0].trim();

    } catch (error) {
        console.error("Error loading patient data:", error);
    }
}

// Global Vapi Instance
let vapi = null;
let isCallActive = false;

async function setupVapi() {
    // Fetch public keys from the backend securely
    let PUBLIC_KEY = "YOUR_VAPI_PUBLIC_KEY";
    let ASSISTANT_ID = "YOUR_ASSISTANT_ID";

    try {
        const configReq = await fetch('/api/config');
        const configData = await configReq.json();
        if (configData.vapi_public_key) PUBLIC_KEY = configData.vapi_public_key;
        if (configData.vapi_assistant_id) ASSISTANT_ID = configData.vapi_assistant_id;
    } catch (e) {
        console.warn("Could not load config from backend. Using fallbacks.");
    }

    try {
        vapi = window.vapiSDK.run({
            apiKey: PUBLIC_KEY,
        });

        const btn = document.getElementById("vapi-btn");
        const statusText = document.getElementById("call-status");
        const btnText = btn.querySelector('.btn-text');
        const icon = btn.querySelector('.mic-icon');

        // Events
        vapi.on('call-start', () => {
            isCallActive = true;
            btn.classList.add('active');
            btn.style.background = "#EF4444";
            btnText.innerText = "End Conversation";
            icon.innerText = "⏹";
            statusText.innerText = "Patient speaking / Listening...";
        });

        vapi.on('call-end', () => {
            isCallActive = false;
            btn.classList.remove('active');
            btn.style.background = "linear-gradient(135deg, var(--secondary), #818CF8)";
            btnText.innerText = "Talk to AI Doctor";
            icon.innerText = "🎤";
            statusText.innerText = "Call ended.";
        });

        vapi.on('speech-start', () => {
            statusText.innerText = "AI is speaking...";
        });

        vapi.on('speech-end', () => {
            statusText.innerText = "Listening...";
        });

        vapi.on('error', (e) => {
            console.error("Vapi Error:", e);
            statusText.innerText = "Failed to connect. Check console.";
        });

        // Click Handler
        btn.addEventListener("click", () => {
            if (isCallActive) {
                vapi.stop();
            } else {
                statusText.innerText = "Connecting...";
                // Start call using the specific assistant ID generated by vapi_setup.py
                vapi.start(ASSISTANT_ID);
            }
        });

    } catch (e) {
        console.error("Vapi SDK Issue:", e);
    }
}

// Optional trigger from "Ask about report" button
window.triggerCall = function () {
    if (!isCallActive) {
        document.getElementById("vapi-btn").click();
    }
}
